#!/usr/bin/env bash
# Build a permissionless, per-build temporary Activity into a C++ byte array.
# The signing key and random package name are generated locally, never committed.
set -euo pipefail
cd "$(dirname "$0")/../.."
out="${1:?usage: tools/startup_ime/build.sh OUTPUT_HEADER}"
case "$out" in /*) ;; *) out="$PWD/$out";; esac
sdk="${ANDROID_SDK_ROOT:-${ANDROID_HOME:-$HOME/Android/Sdk}}"
tools="$sdk/build-tools/35.0.0"
android="$sdk/platforms/android-35/android.jar"
for tool in javac keytool python3 zip; do
    command -v "$tool" >/dev/null || { echo "startup IME: missing $tool" >&2; exit 1; }
done
for file in "$android" "$tools/aapt2" "$tools/d8" "$tools/zipalign" "$tools/apksigner"; do
    [ -e "$file" ] || { echo "startup IME: missing $file; install platforms;android-35 and build-tools;35.0.0" >&2; exit 1; }
done
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
package="com.benzware.keyinput.p$(python3 -c 'import secrets; print(secrets.token_hex(8))')"
python3 - "$package" tools/startup_ime/AndroidManifest.xml.in "$tmp/AndroidManifest.xml" <<'PY'
import pathlib, sys
pathlib.Path(sys.argv[3]).write_text(pathlib.Path(sys.argv[2]).read_text().replace('@PACKAGE@', sys.argv[1]))
PY
mkdir -p "$tmp/classes" "$tmp/dex" "$(dirname "$out")"
javac -source 8 -target 8 -bootclasspath "$android" -d "$tmp/classes" \
    tools/startup_ime/src/com/benzware/keyinput/KeyActivity.java
mapfile -d '' classes < <(find "$tmp/classes" -name '*.class' -print0)
"$tools/d8" --min-api 24 --output "$tmp/dex" "${classes[@]}"
"$tools/aapt2" link -I "$android" --manifest "$tmp/AndroidManifest.xml" -o "$tmp/unsigned.apk"
(cd "$tmp/dex" && zip -q "$tmp/unsigned.apk" classes.dex)
"$tools/zipalign" -f 4 "$tmp/unsigned.apk" "$tmp/aligned.apk"
keytool -genkeypair -keystore "$tmp/ephemeral.p12" -storetype PKCS12 -storepass android \
    -keypass android -alias temporary -keyalg RSA -keysize 2048 -validity 10000 \
    -dname 'CN=Benzware temporary input' >/dev/null 2>&1
"$tools/apksigner" sign --ks "$tmp/ephemeral.p12" --ks-key-alias temporary \
    --ks-pass pass:android --key-pass pass:android --out "$tmp/helper.apk" "$tmp/aligned.apk"
"$tools/apksigner" verify "$tmp/helper.apk"
python3 - "$package" "$tmp/helper.apk" "$out" <<'PY'
import pathlib, sys
package, apk, out = sys.argv[1:]
data = pathlib.Path(apk).read_bytes()
with open(out, 'w', encoding='ascii') as f:
    f.write('// Generated by tools/startup_ime/build.sh; do not commit.\n#pragma once\n')
    f.write('namespace startup_ime_apk {\n')
    f.write(f'inline constexpr char kPackage[] = "{package}";\n')
    f.write('inline constexpr unsigned char kData[] = {\n')
    for i in range(0, len(data), 16):
        f.write('    ' + ','.join(f'0x{x:02x}' for x in data[i:i + 16]) + ',\n')
    f.write('};\n}\n')
print(f'startup IME: embedded temporary helper ({len(data)} bytes)')
PY
