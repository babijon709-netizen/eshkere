#pragma once
#include <sys/types.h>

// Файловый журнал привязки к игре: /data/local/benzware/attach.log.
// Пишет, нашёл ли чит процесс игры, какой транспорт и профиль выбраны, почему
// привязка не прошла (нет процесса / нет libil2cpp / bind не дал доступа /
// классы игры не резолвятся), когда привязка держится и когда отваливается,
// и раз в несколько секунд — живой статус (счётчики чтений, резолв классов,
// локальный игрок). Прошлая сессия уезжает в attach.prev.log.
//
// Одинаковые строки подряд схлопываются («повторено N раз»), поэтому повторяющийся
// отказ привязки не забивает файл. Файл открывается на запись на каждую строку
// (O_APPEND) и сразу закрывается: если процесс упадёт, последняя строка уже на диске.
namespace attachlog {

void say(const char* fmt, ...) __attribute__((format(printf, 1, 2)));

// true раз в `seconds` секунд по монотонным часам; mark — состояние вызывающего
// (static double), чтобы троттлить конкретную строку, а не весь журнал.
bool due_every(double seconds, double& mark);

const char* backend_name(int backend);

} // namespace attachlog
